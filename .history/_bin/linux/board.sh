#!/usr/bin/env bash
# Board UI: read-only projection of .history/ into a single HTML page.
# The HTML owns NO state — every figure is recomputed from the files on
# each generation. Two modes:
#   bash board.sh                 # write .history/board.html (one-shot)
#   bash board.sh serve [port]    # localhost server: each GET regenerates
# Refresh button in the page just reloads — under serve mode that means
# "re-run the generator" (the browser cannot run bash; the server does).
# File references are rendered as IDE deep links (jetbrains://open?file=),
# falling back to plain monospace paths when IDE_SCHEME is unset.
# Env: PORT (default 8791), IDE_SCHEME (default jetbrains — set empty to
# disable links), BOARD_OUT (default .history/board.html),
# BOARD_REFRESH_SECS (default 180 — auto-refresh interval; 0 disables it).
# Plane messages carry a kind: marker — `- <date> — plane (<verb>)
# kind:<question|decision|blocker|status|handoff> <text>` — the board
# renders each as a filterable chip row (no marker → uncategorized, never
# dropped). The static file is also regenerated by plane-watch.sh after a
# non-empty diff, so it stays fresh without serve mode.
# Resolves the project root from the script's own location, so it runs
# from any cwd (repo root, inside _bin/, absolute path) against the
# installed project's .history/.
set -u
cd "$(dirname "$0")/../../.." || exit 1

PORT="${PORT:-8791}"
BOARD_OUT="${BOARD_OUT:-.history/board.html}"
IDE="${IDE_SCHEME-jetbrains}"

link_file() {  # $1 = absolute path, $2 = display text
  # Product code ("idea") is mandatory between scheme and /open — the Toolbox
  # daemon routes on it; a bare jetbrains://open?file=… is rejected with
  # IllegalArgumentException in CommandLineProcessor (idea.log 2026-11-04).
  if [ -n "$IDE" ]; then
    printf '<a href="%s://idea/open?file=%s" title="open in IDE">%s</a>' "$IDE" "$1" "$2"
  else
    printf '%s' "$2"
  fi
}

abs() { printf '%s/%s' "$PWD" "$1"; }

# ---------- parsing ----------
gen_html() {
  local t d status row phase state fresh wl age
  # KPIs + rows
  local blocked=0 awaiting=0 executing=0 delivered=0 live_rows="" archived_n=0
  local plane_rows="" claim_rows=""
  local pending_rows="" metric_rows=""

  # pending issues (resolved markers — e.g. "**CLOSED-…" — are skipped)
  for p in .history/_pending/*.md; do
    [ -f "$p" ] || continue
    grep -q '\*\*CLOSED' "$p" && continue
    local base=$(basename "$p" .md)
    pending_rows+="    <li><span class=\"tag\">pending</span> ${base} <span class=\"path\">$(link_file "$(abs "$p")" "open →")</span></li>"$'\n'
  done
  [ -n "$pending_rows" ] || pending_rows='    <li class="empty">no pending issues</li>'

  # TASK_LIST ### lines → status per task
  declare -A TSTATUS
  if [ -f .history/TASK_LIST.md ]; then
    while IFS= read -r line; do
      # status = FIRST token of the text after the em-dash (later prose may
      # name other statuses fixture-style; the first token is the live one)
      local name=$(printf '%s' "$line" | sed -E 's/^### ([0-9]{4}-[0-9]{2}-[0-9]{2}-)?([^ ]+).*/\2/')
      local s=$(printf '%s' "$line" | sed -E 's/^[^—]*— ?//' | grep -oE 'PLANNED|IN_PROGRESS|IN_REVIEW|DONE|DELIVERED|BLOCKED' | head -1)
      [ -n "$s" ] && TSTATUS[$name]="$s"
    done < <(grep -E '^### ' .history/TASK_LIST.md)
  fi

  # live task dirs (newest 6 with workers.md), status + last state + freshness
  local dirs=$(ls -dt .history/*/ 2>/dev/null | grep -vE '_bin|_templates|_pending|_shared' | head -8)
  for d in $dirs; do
    local name="${d#.history/}"; name="${name%/}"
    local short=$(printf '%s' "$name" | sed -E 's/^[0-9]{4}-[0-9]{2}-[0-9]{2}-//')
    [ -f "${d}workers.md" ] || continue
    local st="${TSTATUS[$short]:-?}"
    # claim row: last table row, status = status-col cell (we have no header
    # map here; take whole row trimmed — the plane knows its own ledger)
    local marker=$(grep -E '^\| [0-9]+ ' "${d}workers.md" | tail -1 | cut -c1-40)
    local rowstatus=""
    case "$st" in DELIVERED|DONE) ;; *)
    rowstatus=$(awk -F'|' '
      function trim(x){gsub(/^ +| +$/,"",x); return x}
      /^\|[ ]*#[ ]*\|/ && hdr!=1 {for(i=2;i<=NF;i++){h=trim($i); sub(/#.*/,"",h); if(h=="Status") si=i} ; hdr=1}
      /^\|[ ]*[0-9]+[ ]*\|/ {if(!si) exit; r=trim($si)}
      END{if(r!="")print r}' "${d}workers.md" | cut -d' ' -f1)
    case "$rowstatus" in
      GRANTED|EXECUTING|DECLARED|STALE|CHALLENGED) executing=$((executing+1)); claim_rows+="    <li><span class=\"tag r\">$rowstatus</span> ${d#.history/} — ${marker#| }…</li>"$'\n' ;;
    esac ;;
    esac
    local wstate=$(grep -E '^state: ' "${d}worklog.md" 2>/dev/null | tail -1 | sed 's/^state: //')
    local wl="${d}worklog.md"
    local age=∞
    if [ -f "$wl" ]; then
      local mtime=$(stat -c %Y "$wl" 2>/dev/null || stat -f %m "$wl" 2>/dev/null)
      [ -n "$mtime" ] && age=$(( ($(date +%s) - mtime + 59) / 60 ))m
    fi
    local state_html="<span class=\"tag\">${wstate:-no state line}</span>"
    case "$wstate" in
      BLOCKED*) state_html="<span class=\"tag b\">${wstate}</span>"; blocked=$((blocked+1)) ;;
      WAITING*) state_html="<span class=\"tag w\">${wstate}</span>" ;;
      ACTIVE*)  state_html="<span class=\"tag r\">${wstate}</span>" ;;
    esac
    case "$st" in
      DELIVERED|DONE) delivered=$((delivered+1)); continue ;;
      *) ;;
    esac
    live_rows+="    <tr><td>$(link_file "$(abs "${d%/}")" "$short")</td><td class=\"st $st\">$st</td><td>$marker</td><td>$state_html</td><td>$age</td></tr>"$'\n'
  done
  [ -n "$live_rows" ] || live_rows='    <tr><td colspan="5" class="empty">no live tasks</td></tr>'

  # plane status: lock freshness (plane session liveness)
  local plane_html=""
  if [ -f .history/plane.lock ]; then
    local lk=$(head -1 .history/plane.lock)
    local ltime=$(printf '%s' "$lk" | grep -oE '2[0-9]{3}-[0-9]{2}-[0-9]{2}T[0-9:]+Z')
    local lage="?"; fresh=stale
    if [ -n "$ltime" ]; then
      local lts=$(date -d "$ltime" +%s 2>/dev/null || date -j -f '%Y-%m-%dT%H:%M:%SZ' "$ltime" +%s 2>/dev/null)
      [ -n "$lts" ] && lage=$(( ($(date +%s) - lts + 59) / 60 ))m
    fi
    printf '%s' "$lk" | grep -q '^released' && plane_html="<li><span class=\"tag\">released</span> no active plane</li>" || {
      local lstyle=b llabel=stale
      if [ "${lage%m}" -le 10 ] 2>/dev/null; then lstyle=r; llabel=fresh; fi
      plane_html="<li><span class=\"tag $lstyle\">$llabel</span> holder ${lk%% *} · lock heartbeat ${lage} ago $(link_file "$(abs .history/plane.lock)" "plane.lock →")</li>"
    }
  else
    plane_html="<li><span class=\"tag b\">no lock</span> plane never booted or lock removed</li>"
  fi
  plane_rows="$plane_html$claim_rows"
  [ -n "$claim_rows" ] || plane_rows="$plane_rows    <li class=\"empty\">no active claim rows (workers idle/absent)</li>"

  # latest plane messages: newest '— plane (' entries across all worklogs.
  # kind: marker right after the verb paren is the category (closed set);
  # no marker (legacy lines) → uncategorized, never dropped. The marker is
  # stripped from the displayed text; counts cover the shown 8 only.
  local plane_msg_rows="" plane_msg_chips=""
  local n_all=0 n_question=0 n_decision=0 n_blocker=0 n_status=0 n_handoff=0 n_uncategorized=0
  while IFS=$'\t' read -r pm_when pm_task pm_text pm_kind; do
    [ -n "$pm_task" ] || continue
    [ -n "$pm_kind" ] || pm_kind="uncategorized"
    local kcls=""
    case "$pm_kind" in
      question) n_question=$((n_question+1)); kcls="q" ;;
      decision) n_decision=$((n_decision+1)); kcls="r" ;;
      blocker) n_blocker=$((n_blocker+1)); kcls="b" ;;
      status) n_status=$((n_status+1)); kcls="w" ;;
      handoff) n_handoff=$((n_handoff+1)); kcls="p" ;;
      *) pm_kind="uncategorized"; n_uncategorized=$((n_uncategorized+1)) ;;
    esac
    n_all=$((n_all+1))
    plane_msg_rows+="    <li data-cat=\"$pm_kind\"><span class=\"tag p\">$pm_when</span><span class=\"tag $kcls\">$pm_kind</span> ${pm_task} — ${pm_text:0:140}</li>"$'\n'
  done < <(awk '
      FNR==1 { task=FILENAME; sub(/^\.history\//,"",task); sub(/\/worklog\.md$/,"",task) }
      /^- [0-9]{4}-[0-9]{2}-[0-9]{2}.*— plane \(/ {
        line=$0
        when=line; sub(/^- /,"",when); sub(/ —.*$/,"",when)
        txt=line; sub(/^.*— plane /,"",txt)
        kind="uncategorized"
        if (match(txt, /^\([^)]*\) kind:(question|decision|blocker|status|handoff)/)) {
          kind=substr(txt, RSTART, RLENGTH); sub(/^.*kind:/, "", kind)
        }
        sub(/kind:[A-Za-z]+ ?/, "", txt); gsub(/</,"&lt;",txt)
        print when "\t" task "\t" txt "\t" kind
      }' .history/*/worklog.md 2>/dev/null | sort -r | head -8)
  [ -n "$plane_msg_rows" ] || plane_msg_rows='    <li class="empty">no plane entries in worklogs yet</li>'
  plane_msg_chips="    <div class=\"chips\"><button class=\"chip on\" onclick=\"filterMsgs('all',this)\">All ($n_all)</button><button class=\"chip\" onclick=\"filterMsgs('question',this)\">question ($n_question)</button><button class=\"chip\" onclick=\"filterMsgs('decision',this)\">decision ($n_decision)</button><button class=\"chip\" onclick=\"filterMsgs('blocker',this)\">blocker ($n_blocker)</button><button class=\"chip\" onclick=\"filterMsgs('status',this)\">status ($n_status)</button><button class=\"chip\" onclick=\"filterMsgs('handoff',this)\">handoff ($n_handoff)</button><button class=\"chip\" onclick=\"filterMsgs('uncategorized',this)\">uncategorized ($n_uncategorized)</button></div>"

  # awaiting you: open Q rows (both formats) + open F adjudications + BLOCKED clearer:human
  # Legacy qa format: pipe rows | Qn | ... |.  v5.x format: '### Qn — title?' with
  # **An:** *(human fills)* A-slots. Same duality for review findings (| Fn | vs
  # '### Fn — ...' with Adjudication A-slot un-filled).
  local await_rows=""
  for d in $dirs; do
    local dshort=$(printf '%s' "${d#.history/}" | sed 's:/*$::; s/^[0-9-]*//')
    case "${TSTATUS[$dshort]:-}" in DELIVERED|DONE) continue ;; esac
    if [ -f "${d}qa.md" ]; then
      # v5.x heading format: '### Qn' blocks whose **An:** still says (human fills)
      local qn_open=""
      while IFS= read -r -d $'\x1e' blk; do
        local qid=$(printf '%s' "$blk" | grep -m1 '^### ' | sed -E 's/^### (Q[0-9]+).*/\1/')
        local qt=$(printf '%s' "$blk" | grep -m1 '^### ' | sed -E 's/^### Q[0-9]+ — ?//' | cut -c1-80)
        printf '%s' "$blk" | awk '{i=index($0,"(human fills"); if(i==0)next; seg=substr($0,i); j=index(seg,")"); rest=substr(seg,j+1); gsub(/[* \t]/,"",rest); if(rest=="")found=1} END{exit !found}' && qn_open+="<li><span class=\"tag q\">$qid</span> ${d#.history/} — ${qt} <span class=\"path\">$(link_file "$(abs "${d%/}/qa.md")" "qa.md →")</span></li>"$'\n'
      done < <(awk '/^### Q[0-9]/{if(buf!="")print buf"\n@@BLK@@"; buf=""} /^### Q[0-9]/{inb=1} inb{buf=buf"\n"$0} END{if(buf!="")print buf"\n@@BLK@@"}' "${d}qa.md" | sed 's/^@@BLK@@$/\x1e/' )
      # legacy pipe format
      while IFS= read -r q; do
        local qn=$(printf '%s' "$q" | cut -d'|' -f2 | tr -d ' ')
        local first=$(printf '%s' "$q" | cut -d'|' -f4 | cut -c1-90)
        qn_open+="    <li><span class=\"tag q\">$qn</span> ${d#.history/} — ${first}… <span class=\"path\">$(link_file "$(abs "${d%/}/qa.md")" "qa.md →")</span></li>"$'\n'
      done < <(grep -E '^\| Q[0-9]+' "${d}qa.md" | grep -vE 'ANSWERED|CONSUMED|SUPERSEDED|N/A' | head -3)
      await_rows+="$qn_open"
    fi
    if [ -f "${d}review.md" ]; then
      while IFS= read -r -d $'\x1e' blk; do
        local fid=$(printf '%s' "$blk" | grep -m1 '^### ' | sed -E 's/^### (F[0-9]+).*/\1/')
        local ft=$(printf '%s' "$blk" | grep -m1 '^### ' | sed -E 's/^### F[0-9]+ — //' | cut -c1-75)
        printf '%s' "$blk" | grep -q 'Adjudication A-slot' && printf '%s' "$blk" | awk '{i=index($0,"(human fills"); if(i==0)next; seg=substr($0,i); j=index(seg,")"); rest=substr(seg,j+1); gsub(/[* \t]/,"",rest); if(rest=="")found=1} END{exit !found}' \
          && await_rows+="    <li><span class=\"tag f\">$fid</span> ${d#.history/} — ${ft} <span class=\"path\">$(link_file "$(abs "${d%/}/review.md")" "review.md →")</span></li>"$'\n'
      done < <(awk '/^### F[0-9]/{if(buf!="")print buf"\n@@BLK@@"; buf=""} /^### F[0-9]/{inb=1} inb{buf=buf"\n"$0} END{if(buf!="")print buf"\n@@BLK@@"}' "${d}review.md" | sed 's/^@@BLK@@$/\x1e/' )
    fi
  done
  for d in $dirs; do
    local bs=$(grep -E '^state: BLOCKED.*clearer:human' "${d}worklog.md" 2>/dev/null | tail -1)
    [ -n "$bs" ] && await_rows+="    <li><span class=\"tag b\">BLOCKED</span> ${d#.history/} — ${bs} <span class=\"path\">$(link_file "$(abs "${d%/}/worklog.md")" "worklog.md →")</span></li>"$'\n'
  done
  [ -n "$await_rows" ] || await_rows='    <li class="empty">nothing is waiting on you</li>'
  awaiting=$(printf '%s' "$await_rows" | grep -c '<li>' || true)

  # auto-refresh: meta tag, BOARD_REFRESH_SECS seconds (default 180, 0 disables)
  local refresh_secs="${BOARD_REFRESH_SECS:-180}"
  local refresh_meta=""
  [ "$refresh_secs" != "0" ] && refresh_meta="<meta http-equiv=\"refresh\" content=\"$refresh_secs\">"

  cat > "$BOARD_OUT" <<HTML
