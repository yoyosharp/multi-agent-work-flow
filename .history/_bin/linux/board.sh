# ---------- serve mode ----------
serve_mode() {
  local port="${1:-$PORT}"
  command -v python3 >/dev/null || { echo "serve mode needs python3"; exit 1; }
  echo "board server on http://localhost:$port (Ctrl-C to stop)"
  python3 - "$port" "$(abs "$0")" <<'PYEOF'
import http.server, socketserver, subprocess, sys, os
port = int(sys.argv[1]); script = sys.argv[2]
class H(http.server.BaseHTTPRequestHandler):
    def do_GET(self):
        subprocess.run(['bash', script])
        # board.sh already cd'ed+wrote; serve the file
        with open(os.environ.get('BOARD_OUT', '.history/board.html'), 'rb') as f:
            body = f.read()
        self.send_response(200)
        self.send_header('Content-Type', 'text/html; charset=utf-8')
        self.send_header('Content-Length', str(len(body)))
        self.end_headers()
        self.wfile.write(body)
    def log_message(self, *a): pass
with socketserver.TCPServer(('127.0.0.1', port), H) as s:
    s.serve_forever()
PYEOF
}

case "${1:-}" in
  serve) shift; serve_mode "${1:-$PORT}" ;;
  *)     gen_html "${1:-}" ;;
esac
