  for ti in "${!TASK_DIRS[@]}"; do
    gen_task_page "${TASK_DIRS[$ti]}" "${TASK_SHORTS[$ti]}"
  done
  prune_task_pages
}

# ---------- serve mode ----------
serve_mode() {
  local port="${1:-$PORT}"
  command -v python3 >/dev/null || { echo "serve mode needs python3"; exit 1; }
  echo "board server on http://localhost:$port (Ctrl-C to stop)"
  BOARD_SERVE=1 python3 - "$port" "$(abs "$0")" <<'PYEOF'
import datetime, hashlib, http.server, os, re, socketserver, subprocess, sys, tempfile, urllib.parse

port = int(sys.argv[1]); script = sys.argv[2]; root = os.getcwd()
BOARD_OUT = os.environ.get('BOARD_OUT', '.history/board.html')

def regen():
    env = dict(os.environ); env['BOARD_SERVE'] = '1'
    subprocess.run(['bash', script], env=env)

def valid_task(task):
    return bool(task) and re.fullmatch(r'[A-Za-z0-9._-]+', task) and '..' not in task \
        and os.path.isdir(os.path.join(root, '.history', task))

def short_of(task):
    return re.sub(r'^\d{4}-\d{2}-\d{2}-', '', task)

def trace_line(task, items):
    wl = os.path.join(root, '.history', task, 'worklog.md')
    now = datetime.datetime.now().strftime('%Y-%m-%d %H:%M')
    prefix = ''
    try:
        with open(wl, 'rb') as f:
            data = f.read()
        if data and not data.endswith(b'\n'):
            prefix = '\n'
    except FileNotFoundError:
        pass
    with open(wl, 'a', encoding='utf-8') as f:
        f.write(prefix + '- %s — human (board) kind:decision submitted %s (fill+release via board)\n' % (now, items))

class H(http.server.BaseHTTPRequestHandler):
    def _send(self, code, body, ctype='text/html; charset=utf-8', extra=None):
        if isinstance(body, str):
            body = body.encode('utf-8')
        self.send_response(code)
        self.send_header('Content-Type', ctype)
        self.send_header('Content-Length', str(len(body)))
        for k, v in (extra or {}).items():
            self.send_header(k, v)
        self.end_headers()
        self.wfile.write(body)

    def _redirect(self, loc):
        self._send(303, 'redirecting to %s' % loc, extra={'Location': loc})

    def _err(self, code, msg):
        self._send(code, '<!DOCTYPE html><html><body><h1>%d</h1><p>%s</p><p><a href="/">← board</a></p></body></html>' % (code, msg))

    def do_GET(self):
        path = urllib.parse.urlparse(self.path).path
        regen()
        if path in ('', '/'):
            target = BOARD_OUT
        else:
            m = re.fullmatch(r'/task/([A-Za-z0-9._-]+)', path) or re.fullmatch(r'/board/([A-Za-z0-9._-]+)\.html', path)
            if not m:
                return self._err(404, 'not found')
            target = os.path.join('.history', 'board', m.group(1) + '.html')
        try:
            with open(target, 'rb') as f:
                body = f.read()
        except FileNotFoundError:
            return self._err(404, 'no such page — regenerate the board')
        self._send(200, body)

    def _form(self):
        n = int(self.headers.get('Content-Length') or 0)
        raw = self.rfile.read(n).decode('utf-8') if n else ''
        qs = urllib.parse.parse_qs(raw)
        return {k: v[0] for k, v in qs.items()}

    def do_POST(self):
        path = urllib.parse.urlparse(self.path).path
        form = self._form()
        if path == '/fill':
            return self._fill(form)
        if path == '/relay':
            return self._relay(form)
        return self._err(404, 'not found')

    def _fill(self, form):
        # Explicit Submit only: fill A-slots + flip status rows to RELEASED
        # (fill+release in one step). Hash-guarded: a file that changed
        # since the page was rendered is never overwritten (409, no write).
        # All items are validated before any write — no partial batches.
        task = form.get('task', ''); fname = form.get('file', ''); h = form.get('hash', '')
        if not valid_task(task) or fname not in ('qa.md', 'review.md'):
            return self._err(400, 'bad task or file')
        path = os.path.join(root, '.history', task, fname)
        try:
            with open(path, 'rb') as f:
                data = f.read()
        except FileNotFoundError:
            return self._err(404, 'file not found')
        if hashlib.sha256(data).hexdigest() != h:
            return self._err(409, 'file changed since page load — reload the page and re-enter your draft. Nothing was written.')
        lines = data.decode('utf-8').split('\n')
        items = []  # (id, value, note)
        if fname == 'qa.md':
            for k, v in form.items():
                if k.startswith('q_') and v.strip():
                    items.append((k[2:], v.strip(), ''))
        else:
            for k, v in form.items():
                if k.startswith('f_') and v.strip():
                    if v.strip() not in ('FIX', 'DROP', 'DEFER'):
                        return self._err(422, 'bad verdict for %s' % k[2:])
                    items.append((k[2:], v.strip(), form.get('fnote_' + k[2:], '').strip()))
        if not items:
            return self._err(422, 'nothing to submit — every field was empty. Nothing was written.')
        # status-table Status column (from the header row, never positional)
        si = None
        for ln in lines:
            if ln.startswith('| #'):
                cells = ln.split('|')
                for i, c in enumerate(cells):
                    if c.strip().split(' ')[0] == 'Status':
                        si = i
                break
        new = list(lines)
        labels = []
        for iid, value, note in items:
            start = None
            for i, ln in enumerate(new):
                if re.match(r'^### %s(\s|—|$)' % re.escape(iid), ln):
                    start = i
                    break
            if start is None:
                return self._err(422, 'block %s not found. Nothing was written.' % iid)
            end = len(new)
            for j in range(start + 1, len(new)):
                if new[j].startswith('### '):
                    end = j
                    break
            slot = None
            for j in range(start, end):
                if fname == 'qa.md' and '**An:**' in new[j]:
                    slot = j; break
                if fname == 'review.md' and '**Adjudication A-slot**' in new[j]:
                    slot = j; break
            if slot is None:
                return self._err(422, 'A-slot for %s not found. Nothing was written.' % iid)
            if fname == 'qa.md':
                new[slot] = re.sub(r'\*\*An:\*\*.*$', lambda m: '**An:** ' + value, new[slot])
                labels.append(iid)
            else:
                repl = '**Adjudication A-slot**: ' + value + ((' (' + note + ')') if note else '')
                new[slot] = re.sub(r'\*\*Adjudication A-slot\*\*:.*$', lambda m: repl, new[slot])
                labels.append('%s=%s' % (iid, value))
            if si is not None:
                for j, ln in enumerate(new):
                    if re.match(r'^\|\s*%s\s*\|' % re.escape(iid), ln):
                        cells = ln.split('|')
                        if si < len(cells):
                            cells[si] = ' RELEASED '
                            new[j] = '|'.join(cells)
                        break
        fd, tmp = tempfile.mkstemp(dir=os.path.dirname(path))
        with os.fdopen(fd, 'w', encoding='utf-8') as f:
            f.write('\n'.join(new))
        os.replace(tmp, path)
        trace_line(task, ', '.join(labels))
        self._redirect('/task/%s?submitted=1' % short_of(task))

    def _relay(self, form):
        # One explicit button per relay; appends ONE canonical inbox row
        # (the same shape a human relay in conversation produces).
        task = form.get('task', ''); relay = form.get('relay', ''); note = form.get('note', '').strip()
        if not valid_task(task):
            return self._err(400, 'bad task')
        short = short_of(task)
        table = {
            'plan-approved': ('plan', 'PLAN-APPROVED %s' % short + ((' — ' + note) if note else '')),
            'waive': ('manual-test', 'WAIVE %s — %s' % (short, note)),
            'final-review': ('final-review', 'FINAL-REVIEW-CONFIRMED %s — solved' % short),
            'delivery-approved': ('delivery', 'DELIVERY-APPROVED %s' % short + ((' — ' + note) if note else '')),
        }
        if relay not in table:
            return self._err(400, 'unknown relay')
        if relay == 'waive' and not note:
            return self._err(422, 'WAIVE needs a reason. Nothing was written.')
        phase, msg = table[relay]
        inbox = os.path.join(root, '.history', task, 'inbox.md')
        ts = datetime.datetime.now().astimezone().strftime('%Y-%m-%d %H:%M %z')
        prefix = ''
        try:
            with open(inbox, 'rb') as f:
                data = f.read()
            if data and not data.endswith(b'\n'):
                prefix = '\n'
        except FileNotFoundError:
            pass
        with open(inbox, 'a', encoding='utf-8') as f:
            f.write(prefix + '| %s | human | plane | %s | %s |\n' % (ts, phase, msg))
        trace_line(task, msg)
        self._redirect('/task/%s?submitted=1' % short)

    def log_message(self, *a):
        pass

socketserver.TCPServer.allow_reuse_address = True
with socketserver.TCPServer(('127.0.0.1', port), H) as s:
    s.serve_forever()
PYEOF
}

