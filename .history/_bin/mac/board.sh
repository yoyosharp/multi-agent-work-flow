prune_task_pages() {  # drop task pages whose task dir no longer exists
  # gen writes pages but a deleted/renamed task (or a transient selftest
  # fixture dir) would otherwise leave a stale page behind forever
  # (live find 2026-11-23: relay-gate-selftest.html outlived its fixture).
  local f base keep t
  [ -d .history/board ] || return 0
  for f in .history/board/*.html; do
    [ -f "$f" ] || continue
    base=$(basename "$f" .html)
    keep=0
    for t in "${TASK_SHORTS[@]}"; do [ "$t" = "$base" ] && { keep=1; break; }; done
    if [ "$keep" -eq 0 ]; then rm -f "$f"; echo "board: pruned stale task page $f"; fi
  done
  return 0  # a kept page must not leak a false status — plane-watch's
            # regen_board treats board.sh's exit code as regen success
}

gen_all() {
  collect_tasks
